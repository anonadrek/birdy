/*
 * The open-source licence list in the app (release 1.3.0, legal review 7i-fix B) is generated by
 * tools/licenses/generate.py from the release build's dependencies. These two tasks give the
 * generator its input and stop a release whose dependencies changed after the list was made.
 * Both resolve only the dependency graphs (no artifact is downloaded or built), which keeps them
 * cheap enough for CI.
 *
 * What ships is the union of two graphs: the release runtime classpath, and the core library
 * desugaring library (desugar_jdk_libs), which D8/L8 compile into the app's dex for java.time and
 * the other Java APIs older Android versions lack.
 */

/** Writes the release build's external dependencies, one `group:name:version` per line, sorted. */
abstract class WriteReleaseDependenciesTask : DefaultTask() {
    @get:Input
    abstract val rootComponent: Property<ResolvedComponentResult>

    @get:Input
    abstract val desugaringRootComponent: Property<ResolvedComponentResult>

    @get:OutputFile
    abstract val output: RegularFileProperty

    @TaskAction
    fun write() {
        val file = output.get().asFile
        file.parentFile.mkdirs()
        val modules = externalModules(rootComponent.get(), desugaringRootComponent.get())
        file.writeText(modules.joinToString(separator = "\n", postfix = "\n"))
    }
}

/**
 * Fails when the release build's external dependencies differ from [committedList]
 * (tools/licenses/release-dependencies.txt, written by tools/licenses/generate.py together with
 * the licence files the app shows).
 */
abstract class VerifyLicenseListTask : DefaultTask() {
    @get:Input
    abstract val rootComponent: Property<ResolvedComponentResult>

    @get:Input
    abstract val desugaringRootComponent: Property<ResolvedComponentResult>

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val committedList: RegularFileProperty

    @TaskAction
    fun verify() {
        val fresh = externalModules(rootComponent.get(), desugaringRootComponent.get()).toSet()
        val committed =
            committedList
                .get()
                .asFile
                .readLines()
                .map { it.trim() }
                .filter { it.isNotEmpty() && !it.startsWith("#") }
                .toSet()
        val added = (fresh - committed).sorted()
        val removed = (committed - fresh).sorted()
        if (added.isNotEmpty() || removed.isNotEmpty()) {
            throw GradleException(
                buildString {
                    appendLine("The release dependencies changed, so the licence list in the app is out of date.")
                    if (added.isNotEmpty()) appendLine("New: ${added.joinToString()}")
                    if (removed.isNotEmpty()) appendLine("Gone: ${removed.joinToString()}")
                    append(
                        "Regenerate it with `uv run --with fonttools python tools/licenses/generate.py` " +
                            "and commit the result.",
                    )
                },
            )
        }
    }
}

/** Every external module (not this build's own projects) reachable from any of [roots], sorted. */
internal fun externalModules(vararg roots: ResolvedComponentResult): List<String> {
    val seen = mutableSetOf<ComponentIdentifier>()
    val modules = sortedSetOf<String>()
    val queue = ArrayDeque<ResolvedComponentResult>()
    // Every root is this project itself (the same component id in each graph), so the roots are
    // never deduplicated; only what they depend on is.
    roots.forEach { root -> queue.addAll(root.selectedDependencies()) }
    while (queue.isNotEmpty()) {
        val component = queue.removeFirst()
        if (!seen.add(component.id)) continue
        (component.id as? ModuleComponentIdentifier)?.let { modules += "${it.group}:${it.module}:${it.version}" }
        queue.addAll(component.selectedDependencies())
    }
    return modules.toList()
}

private fun ResolvedComponentResult.selectedDependencies(): List<ResolvedComponentResult> =
    dependencies
        .filterIsInstance<ResolvedDependencyResult>()
        .filter { !it.isConstraint }
        .map { it.selected }

/**
 * Writes the files of the release build's external dependencies, one `group:name:version<TAB>path`
 * per line, for tools/licenses/generate.py to read the notices inside them (Google's AARs carry
 * third_party_licenses.txt). The files are the ones the build itself resolves, downloaded by Gradle
 * if needed, so the generator never depends on what happens to be in a local cache. Only the
 * generator runs this task; the guard above needs no files.
 */
abstract class WriteReleaseArtifactsTask : DefaultTask() {
    /** `group:name:version<TAB>path` per file; see [artifactLines]. */
    @get:Input
    abstract val lines: ListProperty<String>

    @get:OutputFile
    abstract val output: RegularFileProperty

    init {
        outputs.upToDateWhen { false }
    }

    @TaskAction
    fun write() {
        val file = output.get().asFile
        file.parentFile.mkdirs()
        file.writeText(lines.get().toSortedSet().joinToString(separator = "\n", postfix = "\n"))
    }
}

/**
 * The external modules' files among [artifacts] as `group:name:version<TAB>path` lines. A plain
 * list of strings, so that the task input is configuration-cache safe (resolved artifact results
 * are not).
 */
fun artifactLines(artifacts: Provider<Set<ResolvedArtifactResult>>): Provider<List<String>> =
    artifacts.map { results ->
        results.mapNotNull { artifact ->
            val id = artifact.id.componentIdentifier as? ModuleComponentIdentifier
            id?.let { "${it.group}:${it.module}:${it.version}\t${artifact.file.absolutePath}" }
        }
    }
